import AppKit
import CryptoKit
import ImageIO

/// Checks the clipboard's change count every 0.3 s and adds each new copy to the history.
final class ClipboardWatcher {
    private let pb = NSPasteboard.general
    private let history: History
    private var lastChange: Int
    private var timer: Timer?

    /// Menu bar › Pause Recording. Copies made while paused are not kept.
    var paused: Bool {
        get { UserDefaults.standard.bool(forKey: "paused") }
        set { UserDefaults.standard.set(newValue, forKey: "paused") }
    }

    init(history: History) {
        self.history = history
        lastChange = pb.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after writing to the clipboard ourselves, so pasting from the history isn't recorded
    /// as a new copy.
    func skipCurrent() { lastChange = pb.changeCount }

    private func check() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }
        let front = NSWorkspace.shared.frontmostApplication
        var source = (name: front?.localizedName, app: front?.bundleIdentifier)
        if let front, let ext = BrowserExtensions.source(in: front, wanted: AutoClear.shared.apps) {
            source = (ext.name, ext.app)
        }
        // A password manager's copies stay out, unless an auto-clear rule lets them in for a while.
        let rule = AutoClear.shared.rule(for: source.app)
        if rule == nil, let id = source.app, Self.ignoredApps.contains(id) { return }
        guard let (clip, reps) = Self.capture(pb, sourceName: source.name, sourceApp: source.app,
                                              keepMarked: rule != nil) else { return }
        history.add(clip, reps: reps)
    }

    /// Password managers and Keychain: nothing copied in them is kept, unless an auto-clear rule
    /// covers the app.
    static let ignoredApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.Passwords", "com.apple.keychainaccess", "org.keepassxc.keepassxc",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
    ]

    /// Markers apps add to a copy that clipboard managers should leave alone (nspasteboard.org):
    /// passwords, one-off and generated copies.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    /// The formats kept. Reading every format an app offers can make it render each one (Excel,
    /// Keynote), so only these are read; they cover text, formatting, links, images and files.
    static let keptTypes: Set<String> = [
        "public.utf8-plain-text", "public.rtf", "com.apple.flat-rtfd", "public.html", "com.apple.webarchive",
        "public.url", "public.url-name", "public.file-url", "public.png", "public.tiff", "public.jpeg", "public.heic",
    ]
    private static let maxBytes = 30 * 1024 * 1024

    /// The clip and its pasteboard data for what's on the clipboard now, or nil when there's
    /// nothing worth keeping (empty, a password, or a format the app doesn't show).
    /// `keepMarked` keeps copies marked as concealed too: an auto-clear rule covers the app.
    static func capture(_ pb: NSPasteboard, sourceName: String?, sourceApp: String?, keepMarked: Bool = false) -> (Clip, Reps)? {
        guard let items = pb.pasteboardItems, !items.isEmpty else { return nil }
        let allTypes = Set(items.flatMap { $0.types.map(\.rawValue) })
        guard keepMarked || allTypes.isDisjoint(with: skipTypes) else { return nil }

        var reps: Reps = items.map { item in
            var dict: [String: Data] = [:]
            for t in keptTypes where item.types.contains(NSPasteboard.PasteboardType(t)) {
                if let d = item.data(forType: NSPasteboard.PasteboardType(t)), d.count <= maxBytes { dict[t] = d }
            }
            return dict
        }

        var clip = Clip(id: UUID(), kind: .text, text: "", sourceApp: sourceName,
                        sourceBundleID: sourceApp, copiedAt: Date(), pinned: false,
                        copyCount: 1, fingerprint: "")
        let files = items.compactMap { $0.string(forType: .fileURL).flatMap(URL.init(string:)) }.filter(\.isFileURL)
        let string = pb.string(forType: .string)

        if !files.isEmpty {
            clip.kind = .file
            clip.text = files.map(\.path).joined(separator: "\n")
        } else if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            clip.kind = isLink(string) ? .link : .text
            clip.text = string
        } else if var image = reps.first.flatMap(History.imageData) {
            // Keep one compact copy of an image: PNG. A TIFF is made again when it's pasted.
            if reps[0]["public.png"] == nil, let png = NSBitmapImageRep(data: image)?.representation(using: .png, properties: [:]) {
                image = png
            }
            reps = [["public.png": image]]
            clip.kind = .image
            if let src = CGImageSourceCreateWithData(image as CFData, nil),
               let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
                clip.imageWidth = props[kCGImagePropertyPixelWidth] as? Int
                clip.imageHeight = props[kCGImagePropertyPixelHeight] as? Int
            }
            clip.fingerprint = "image:" + sha256(image)
            return (clip, reps)
        } else {
            return nil
        }
        clip.fingerprint = clip.kind.rawValue + ":" + sha256(Data(clip.text.utf8))
        return (clip, reps)
    }

    /// One web or mail address on its own.
    static func isLink(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard t.count < 2000, !t.contains(where: \.isWhitespace), let url = URL(string: t),
              let scheme = url.scheme?.lowercased() else { return false }
        if scheme == "mailto" { return true }
        return ["http", "https", "ftp"].contains(scheme) && url.host != nil
    }

    private static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
